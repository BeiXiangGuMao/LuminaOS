/// 克隆子空间（M12-B COW 派生）：全新 4 表骨架 + **零拷贝共享父帧**。
///
/// 与 v0.11 逐字节克隆的差别（克隆成本 O(1) 化）：
/// - **代码帧共享**：子 PT[0] 直映父代码帧物理地址（本就 P|U 只读，
///   零降级零拷贝）；
/// - **栈帧共享 + COW**：子 PT[2] 映射父栈帧，P|U 去 W + COW 标记位
///   （PTE avail bit 9）；**父侧同步降级**（去 W + COW 位）+ invlpg
///   （父任务运行于本核，无跨核击落需求）；任一侧首次写触发 #PF →
///   [`crate::vmm`] 的 COW 分支私拷回写。
/// - 遗传细胞：寄存器协议（r14 ← 父 pid，派发面注入）——共享栈帧
///   不可物理直写，内存细胞随 COW 退役。
///
/// `alloc_frame` 为帧分配器闭包。返回 [`CloneSpace`] 全 6 帧记录
/// （code_frame/stack_frame = 父侧共享帧地址——取证面 t37 v2 对证
/// 代码帧物理同一性；失败路径全量归还新建帧，共享帧不归还）。
pub fn clone_user_space_cow<F>(
    parent_root: u64,
    alloc_frame: &mut F,
) -> Result<CloneSpace, UserSpaceError>
where
    F: FnMut() -> Option<u64>,
{
    // 4 表骨架（无叶帧分配——COW 零拷贝的关键：不产生孤儿帧）
    let (root, pdpt, pd, pt) = build_space_tables(alloc_frame)?;
    let Some(parent_code) = translate(parent_root, USER_CODE_VIRT) else {
        return Err(UserSpaceError::FramesExhausted); // 父代码帧不可达 = 空间残缺
    };
    let Some(parent_stack) = translate(parent_root, USER_STACK_VIRT) else {
        return Err(UserSpaceError::FramesExhausted);
    };
    let Some(parent_pt) = parent_pt_of(parent_root) else {
        return Err(UserSpaceError::FramesExhausted);
    };
    // 子 PT：代码帧共享（P|U 只读）、栈帧 COW（P|U + COW 位，去 W）。
    // PT 帧物理直写（与 build_space_tables 同款恒等写纪律）。
    let cow_bit: u64 = 1 << 9; // PTE avail 位 9：COW 标记（vmm #PF 分支识别）
    ostd::hw::phys::write_u64(pt, Entry::page(parent_code, Entry::USER).bits());
    ostd::hw::phys::write_u64(
        pt + 2 * 8,
        (Entry::page(parent_stack, Entry::USER).bits() & !Entry::WRITABLE) | cow_bit,
    );
    // 父侧栈降级：PT[2] 去 W + COW 位（共享语义对父同步生效）+ invlpg
    // （父任务运行于调用核，无跨核击落需求）。
    let old = ostd::hw::phys::read_u64(parent_pt + 2 * 8);
    ostd::hw::phys::write_u64(parent_pt + 2 * 8, (old & !Entry::WRITABLE) | cow_bit);
    ostd::hw::control::invlpg(USER_STACK_VIRT);
    Ok(CloneSpace {
        root,
        pdpt,
        pd,
        pt,
        code_frame: parent_code,
        stack_frame: parent_stack,
    })
}

/// 父侧栈降级回滚（spawn 后续步骤失败时恢复原 PTE，父侧零残留）。
pub fn rollback_cow_demote(parent_root: u64) {
    if let Some(parent_pt) = parent_pt_of(parent_root) {
        let cur = ostd::hw::phys::read_u64(parent_pt + 2 * 8);
        ostd::hw::phys::write_u64(parent_pt + 2 * 8, (cur & !(1 << 9)) | Entry::WRITABLE);
        ostd::hw::control::invlpg(USER_STACK_VIRT);
    }
}

/// 父根的用户 PT 基址（M12-B COW 降级定位；布局由 build_space_frames
/// 定约：PML4[0]→PDPT[0]→PD[2]→PT）。
fn parent_pt_of(root: u64) -> Option<u64> {
    let pml4e = ostd::hw::phys::read_u64(root) & Entry::ADDR_MASK;
    if pml4e == 0 {
        return None;
    }
    let pdpte = ostd::hw::phys::read_u64(pml4e) & Entry::ADDR_MASK;
    if pdpte == 0 {
        return None;
    }
    let pde = ostd::hw::phys::read_u64(pdpte + 2 * 8) & Entry::ADDR_MASK;
    if pde == 0 {
        return None;
    }
    Some(pde)
}

