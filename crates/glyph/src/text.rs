/// 域外码点判定（ASCII 0x20..=0x7E 之外——v0 '?' 替身域）。
fn needs_replacement(b: u8) -> bool {
    !(ASCII_FIRST..=ASCII_LAST).contains(&b)
}

/// 取一字形的单行位图（`row` 0..16；MSB = 最左像素）。域外码点 /
/// 越界行返回 0（空白行——替身 '?' 字形本身在册，逐字节替身由
/// [`char_bytes`] 承接）。
pub fn glyph_row(ch: char, row: usize) -> u8 {
    if row >= GLYPH_H {
        return 0;
    }
    let b = if (ch as u32) <= 0x7F {
        ch as u32 as u8
    } else {
        REPLACEMENT as u8
    };
    if needs_replacement(b) {
        return 0;
    }
    let idx = (b - ASCII_FIRST) as usize * GLYPH_H * BYTES_PER_ROW + row;
    FONT8X16[idx]
}

/// 取一字形的 16 行字节（逐字节替身：域外码点 → '?' 字形）。
pub fn char_bytes(ch: char) -> [u8; GLYPH_H] {
    let b = if (ch as u32) <= 0x7F {
        ch as u32 as u8
    } else {
        REPLACEMENT as u8
    };
    let mut out = [0u8; GLYPH_H];
    for (r, slot) in out.iter_mut().enumerate() {
        let idx = if needs_replacement(b) {
            (REPLACEMENT as u8 - ASCII_FIRST) as usize * GLYPH_H + r
        } else {
            (b - ASCII_FIRST) as usize * GLYPH_H + r
        };
        *slot = FONT8X16[idx];
    }
    out
}

/// 单行文本宽度（像素）——每码点一格 advance = 8；域外码点替身
/// 同宽如实记档。
pub fn text_width(s: &str) -> usize {
    s.chars().count() * GLYPH_W
}

/// 单行文本渲染（透明合成：字形置位像素覆写 `fg`、清位像素不写；
/// 起点可负可越缘——越界裁剪不 panic）。v0 单行域：换行/控制字符
/// 同替身域处理，多行由调用方逐行调用。
pub fn render_text(dst: &mut [u32], stride: usize, ox: i32, oy: i32, s: &str, fg: u32) {
    let mut pen_x = ox;
    for ch in s.chars() {
        let rows = char_bytes(ch);
        for (r, bits) in rows.iter().enumerate() {
            let py = oy + r as i32;
            if py < 0 {
                continue;
            }
            let py = py as usize;
            let base = py.saturating_mul(stride);
            if base == usize::MAX {
                continue; // 溢出哨兵（py·stride 超界——全行裁剪）
            }
            for c in 0..GLYPH_W {
                if bits & (0x80 >> c) == 0 {
                    continue;
                }
                let px = pen_x + c as i32;
                if px < 0 {
                    continue;
                }
                let col = px as usize;
                if base + col < dst.len() {
                    dst[base + col] = fg;
                }
            }
        }
        pen_x += GLYPH_W as i32;
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;

    /// 两域同源对账锚：'A' / '0' / '~' 三字形 16 行金值
    /// （crates/kernel/src/font_gen.rs 抽样——单事实源
    /// scripts/gen_font8x16.py 的两域副本一致性锚定）。
    #[test]
    fn cross_domain_glyph_anchors() {
        let a = char_bytes('A');
        assert_eq!(
            a,
            [
                0x00, 0x00, 0x00, 0x00, 0x18, 0x1C, 0x3C, 0x34, 0x26, 0x26, 0x7E, 0x43, 0x43, 0xC3,
                0x00, 0x00,
            ]
        );
        let tilde = char_bytes('~');
        assert_eq!(
            tilde,
            [
                0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x79, 0x0E, 0x00, 0x00, 0x00,
                0x00, 0x00,
            ]
        );
        let zero = char_bytes('0');
        // '0' 行 3..13 有像素（形腔位图——非全空白域）。
        assert!(zero.iter().any(|&b| b != 0));
        // 95 字形域：首尾码点行位图索引合法（越界 panic 免疫）。
        assert_eq!(glyph_row(' ', 0), 0x00);
        assert_eq!(glyph_row('~', 15), 0x00);
    }

    /// 宽度核：ASCII / 域外替身同宽域（advance = 8 恒等）。
    #[test]
    fn width_core() {
        assert_eq!(text_width(""), 0);
        assert_eq!(text_width("A"), GLYPH_W);
        assert_eq!(text_width("Lumina"), 6 * GLYPH_W);
        // 非 ASCII 域外替身：逐码点一格（'λ' 单码点 = 8）。
        assert_eq!(text_width("λ"), GLYPH_W);
        assert_eq!(text_width("λx"), 2 * GLYPH_W);
    }

    /// 渲染像素级对账：'A' 置位位 ⇄ 画布前景色、清位位不动背景；
    /// 逐行逐位与 char_bytes 位图一致性。
    #[test]
    fn render_pixel_anchors() {
        let stride = 24;
        let mut fb = [0x11_22_33_44u32; 24 * 24];
        // 背景 ×2 采样点：字形 'A' 行 3 位 7..5 区（0x18 = 0001_1000——
        // 位 4/3 置位；取位 7 = 清位域采样）。
        render_text(&mut fb, stride, 4, 2, "A", 0xFF_00_FF_00);
        let rows = char_bytes('A');
        for (r, bits) in rows.iter().enumerate() {
            for c in 0..GLYPH_W {
                let px = fb[(2 + r) * stride + 4 + c];
                if bits & (0x80 >> c) != 0 {
                    assert_eq!(px, 0xFF_00_FF_00, "r={r} c={c} 应为前景");
                } else {
                    assert_eq!(px, 0x11_22_33_44, "r={r} c={c} 应为背景透传");
                }
            }
        }
    }

    /// 越界裁剪：负起点 / 超缘 / 超画布全谱不 panic + 域内可见部分
    /// 精确落笔。
    #[test]
    fn clip_no_panic() {
        let stride = 16;
        let mut fb = [0u32; 16 * 16];
        // 负 x/y 起点：裁剪后仍可见（'A' 位 4/3 于 py=2 行）。
        render_text(&mut fb, stride, -6, -14, "A", 1);
        // 全程无 panic 即主断言；可见域抽查：
        // 'A' 行 4（0x1C：位 4..2）→ py = -14+4 = -10 仍负——零可见；
        // 行 15 → py = 1 可见（0x00——'A' 尾行空，不落笔）。
        assert_eq!(fb[0], 0, "裁剪域不误写");
        // 超画布缘：全部裁剪不 panic。
        render_text(&mut fb, stride, 16, 0, "ABC", 2);
        render_text(&mut fb, stride, 0, 16, "ABC", 2);
        // 完全越界画布：索引全裁剪。
        render_text(&mut fb, stride, 15, 0, "A", 3);
        render_text(&mut fb, stride, 0, 15, "A", 3);
    }

    /// 替身域：域外码点渲染 ⇄ '?' 字形位图一致（'?' 在册域）。
    #[test]
    fn replacement_glyph() {
        let q = char_bytes('?');
        let repl = char_bytes('λ');
        assert_eq!(q, repl, "域外替身 = '?' 字形逐字节");
        let stride = 16;
        let mut fb = [0u32; 16 * 16];
        render_text(&mut fb, stride, 0, 0, "?", 0xFFFF_FFFF);
        for (r, bits) in q.iter().enumerate() {
            for c in 0..GLYPH_W {
                let px = fb[r * stride + c];
                if bits & (0x80 >> c) != 0 {
                    assert_eq!(px, 0xFFFF_FFFF, "r={r} c={c} 替身前景");
                }
            }
        }
    }
}
